#!/usr/bin/env node
/*
 * dev/gen-history-secret.mjs - write src/history_secret.h without ever printing
 * the ingest key.
 *
 *   node dev/gen-history-secret.mjs
 *   node dev/gen-history-secret.mjs --url https://race-tracker-history.pages.dev/ingest
 *   node dev/gen-history-secret.mjs --key-file C:\path\to\ingest.key --device esp32-01
 *
 * The key is read from %USERPROFILE%\.esp32-race-tracker\ingest.key by default
 * (outside the repo, never committed). The generated header is gitignored.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';

const arg = (name, fallback) => {
  const i = process.argv.indexOf('--' + name);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};

const keyFile = arg('key-file', join(homedir(), '.esp32-race-tracker', 'ingest.key'));
const url = arg('url', 'https://race-tracker-history.pages.dev/ingest');
const device = arg('device', 'esp32-01');
const out = resolve(arg('out', join(process.cwd(), 'src', 'history_secret.h')));

if (!existsSync(keyFile)) {
  console.error(`missing key file: ${keyFile}`);
  console.error('create it with: node -e "require(\'fs\').writeFileSync(process.argv[1], require(\'crypto\').randomBytes(32).toString(\'hex\'))" <path>');
  console.error('then store the same value as the INGEST_KEY secret on the host.');
  process.exit(1);
}

const key = readFileSync(keyFile, 'utf8').trim();
if (!/^[A-Za-z0-9._-]{32,128}$/.test(key)) {
  console.error(`key file does not look like a key (${key.length} chars)`);
  process.exit(1);
}
if (!/^https:\/\/[^\s/]+\//.test(url)) {
  console.error(`--url must be an https URL, got: ${url}`);
  process.exit(1);
}

const header = `// Generated by dev/gen-history-secret.mjs - gitignored, never commit.
// Regenerate after rotating the ingest key.
#pragma once
#define HISTORY_URL     "${url}"
#define HISTORY_KEY     "${key}"
#define HISTORY_DEVICE  "${device}"
#define HISTORY_SELFTEST_EPOCH ${Math.floor(Date.now() / 1000)}UL
`;

writeFileSync(out, header, 'utf8');
console.log(`wrote ${out}`);
console.log(`  url    ${url}`);
console.log(`  device ${device}`);
console.log(`  key    ${key.length} chars from ${keyFile} (not printed)`);
console.log(`  epoch  ${Math.floor(Date.now() / 1000)} (self-test builds only)`);
